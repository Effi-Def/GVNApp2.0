import { defineConfig, loadEnv } from 'vite'
import react from '@vitejs/plugin-react'
import { VitePWA } from 'vite-plugin-pwa'
import { writeFileSync } from 'fs'
import { resolve } from 'path'

// https://vitejs.dev/config/
export default defineConfig(({ mode }) => {
  // Load env from the project root so VITE_* vars are accessible at build time
  const env = loadEnv(mode, process.cwd(), '')

  // Plugin: genera firebase-messaging-sw.js in public/ con le credenziali da .env
  // Questo evita di avere le chiavi Firebase hardcoded in un file pubblico non processato da Vite.
  const generateFcmSwPlugin = {
    name: 'generate-fcm-sw',
    buildStart() {
      const apiKey = env.VITE_FIREBASE_API_KEY || ''
      const authDomain = env.VITE_FIREBASE_AUTH_DOMAIN || ''
      const projectId = env.VITE_FIREBASE_PROJECT_ID || ''
      const storageBucket = env.VITE_FIREBASE_STORAGE_BUCKET || ''
      const messagingSenderId = env.VITE_FIREBASE_MESSAGING_SENDER_ID || ''
      const appId = env.VITE_FIREBASE_APP_ID || ''

      if (!messagingSenderId || !appId) {
        console.warn('[generate-fcm-sw] VITE_FIREBASE_* env vars missing; firebase-messaging-sw.js not regenerated.')
        return
      }

      const content = `importScripts('https://www.gstatic.com/firebasejs/10.7.1/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.7.1/firebase-messaging-compat.js');

// Auto-generated by vite.config.ts from VITE_FIREBASE_* env vars — DO NOT EDIT MANUALLY.
firebase.initializeApp({
  apiKey: "${apiKey}",
  authDomain: "${authDomain}",
  projectId: "${projectId}",
  storageBucket: "${storageBucket}",
  messagingSenderId: "${messagingSenderId}",
  appId: "${appId}"
});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  console.log('[firebase-messaging-sw.js] Received background message ', payload);

  const notificationTitle = payload.notification?.title || 'Nuova notifica';

  const kind = payload.data?.kind || payload.data?.type || 'general';
  const relatedId = payload.data?.relatedId || payload.data?.click_action?.split('/events/')?.[1]?.split('/')?.[0] || '';
  const tag = relatedId ? \`gvnapp-\${kind}-\${relatedId}\` : \`gvnapp-\${kind}\`;

  const notificationOptions = {
    body: payload.notification?.body || '',
    icon: '/icons/pig-192.png',
    badge: '/icons/pig-192.png',
    data: payload.data,
    tag,
    renotify: true,
  };

  self.registration.showNotification(notificationTitle, notificationOptions);
});

self.addEventListener('notificationclick', function(event) {
  console.log('[firebase-messaging-sw.js] Notification click received.');
  event.notification.close();

  const rawUrl = event.notification.data?.click_action || '/';
  const urlToOpen = rawUrl.startsWith('http') ? rawUrl : (self.location.origin + rawUrl);

  event.waitUntil(
    clients.matchAll({ type: 'window', includeUncontrolled: true }).then(function(windowClients) {
      for (let i = 0; i < windowClients.length; i++) {
        const client = windowClients[i];
        if ('focus' in client) {
          if (client.url !== urlToOpen && 'navigate' in client) {
            return client.navigate(urlToOpen).then(function(c) { return c && c.focus(); });
          }
          return client.focus();
        }
      }
      if (clients.openWindow) {
        return clients.openWindow(urlToOpen);
      }
    })
  );
});
`
      const outPath = resolve(process.cwd(), 'public', 'firebase-messaging-sw.js')
      writeFileSync(outPath, content, 'utf-8')
      console.log('[generate-fcm-sw] Generated public/firebase-messaging-sw.js from env vars.')
    },
  }

  return {
  build: {
    // Sourcemaps disabled in production to avoid exposing source code.
    // Enable locally with VITE_SOURCEMAP=true if needed for debugging.
    sourcemap: process.env.VITE_SOURCEMAP === 'true',
    rollupOptions: {
      output: {
        // Split heavy third-party libraries into stable, separately-cacheable chunks.
        // These change only when dependencies are updated, not when app code changes.
        manualChunks: {
          'vendor-react': ['react', 'react-dom', 'react-router-dom'],
          'vendor-firebase-app': ['firebase/app', 'firebase/auth'],
          'vendor-firebase-firestore': ['firebase/firestore'],
          'vendor-firebase-storage': ['firebase/storage'],
          'vendor-firebase-messaging': ['firebase/messaging'],
          'vendor-leaflet': ['leaflet', 'react-leaflet'],
        },
      },
    },
  },
  plugins: [
    react(),
    VitePWA({
      disable: process.env.NODE_ENV === 'development', // CRITICAL: Disable SW in dev to prevent loops
      // On Android/installed PWAs, `prompt` can leave users stuck on an old SW
      // until they manually refresh/accept the update. Prefer automatic updates.
      registerType: 'autoUpdate',
      // Ensure our messaging handlers are included in the generated SW,
      // so we only have ONE service worker at scope '/'
      workbox: {
        importScripts: ['firebase-messaging-sw.js'],
        skipWaiting: true,
        clientsClaim: true,
        cleanupOutdatedCaches: true,
      },
      includeAssets: [
        'icons/pig-maskable.svg',
        'icons/pig-192.png',
        'icons/pig-512.png',
        'icons/apple-touch-icon.png'
      ],
      manifest: {
        name: 'GVNApp - Social Events Hub',
        short_name: 'GVNApp',
        description: 'Progressive Web App per organizzare eventi sociali e gestire spese di gruppo',
        theme_color: '#3B82F6',
        background_color: '#ffffff',
        display: 'standalone',
        scope: '/',
        start_url: '/',
        icons: [
          {
            src: 'icons/pig-192.png',
            sizes: '192x192',
            type: 'image/png'
          },
          {
            src: 'icons/pig-512.png',
            sizes: '512x512',
            type: 'image/png'
          },
          {
            src: 'icons/pig-maskable.svg',
            sizes: 'any',
            type: 'image/svg+xml',
            purpose: 'any maskable'
          },
          {
            src: 'icons/apple-touch-icon.png',
            sizes: '180x180',
            type: 'image/png',
            purpose: 'any'
          }
        ]
      }
    }),
    generateFcmSwPlugin,
  ],
  }
})
